# -*- coding: utf-8 -*-
"""Shared helpers for the swarmtier hooks (stdlib only).

Every hook imports this module. It does four things:
  * puts the plugin root on sys.path so `core` can be imported;
  * reads the hook event from stdin as UTF-8 (never the console codepage);
  * resolves the data directory / config through `core.config` (with safe fallbacks);
  * offers tiny JSON / JSONL helpers so a hook never depends on core internals for I/O.

A hook must never break a session: everything here is defensive.
"""
import io
import json
import os
import re
import sys
import time
from pathlib import Path

PLUGIN_ROOT = os.environ.get("CLAUDE_PLUGIN_ROOT") or str(Path(__file__).resolve().parent.parent)
if PLUGIN_ROOT not in sys.path:
    sys.path.insert(0, PLUGIN_ROOT)

try:
    sys.stdout.reconfigure(encoding="utf-8", errors="replace")
    sys.stderr.reconfigure(encoding="utf-8", errors="replace")
except Exception:  # pragma: no cover - very old/odd streams
    pass

# Blocks generated by the runtime itself, never typed by the user.
SYSTEM_NOISE = re.compile(
    r"<task-notification>|<system-reminder>|\[SYSTEM NOTIFICATION|"
    r"<local-command-|<command-name>|Caveat: The messages below were generated",
    re.I,
)


def read_event():
    """Read the hook event (JSON) from stdin as UTF-8. Returns a dict, or None."""
    try:
        raw = sys.stdin.buffer.read().decode("utf-8", "replace")
        data = json.loads(raw) if raw.strip() else {}
        return data if isinstance(data, dict) else None
    except Exception:
        return None


def load_cfg():
    """Return the merged plugin config (a dict). Empty dict if core is unavailable."""
    try:
        from core.config import load_config
        cfg = load_config()
        return cfg if isinstance(cfg, dict) else {}
    except Exception:
        return {}


def cfg_get(cfg, dotted, default=None):
    """cfg_get(cfg, 'hooks.cold_cache.ttl_minutes', 60) - nested lookup with default."""
    cur = cfg
    for part in dotted.split("."):
        if not isinstance(cur, dict) or part not in cur:
            return default
        cur = cur[part]
    return default if cur is None else cur


def setting(cfg, key, default=None):
    """Flat key from swarmtier.toml (e.g. 'cache_ttl_minutes'); also accepts a [hooks] table."""
    if isinstance(cfg, dict):
        if cfg.get(key) is not None:
            return cfg[key]
        sub = cfg.get("hooks")
        if isinstance(sub, dict) and sub.get(key) is not None:
            return sub[key]
    return default


def get_data_dir():
    """Directory for hook state (created if needed). None if it cannot be resolved."""
    try:
        from core.config import data_dir
        d = Path(data_dir())
        d.mkdir(parents=True, exist_ok=True)
        return d
    except Exception:
        return None


def read_json(path, default):
    try:
        with io.open(str(path), encoding="utf-8") as f:
            return json.load(f)
    except Exception:
        return default


def write_json(path, data):
    """Atomic write (temp file + replace). Silent on failure."""
    try:
        tmp = str(path) + ".tmp"
        with io.open(tmp, "w", encoding="utf-8") as f:
            f.write(json.dumps(data, ensure_ascii=False))
        os.replace(tmp, str(path))
    except Exception:
        pass


def jsonl_append(path, obj):
    try:
        with io.open(str(path), "a", encoding="utf-8") as f:
            f.write(json.dumps(obj, ensure_ascii=False) + "\n")
        return True
    except Exception:
        return False


def jsonl_read(path):
    out = []
    try:
        with io.open(str(path), encoding="utf-8") as f:
            for line in f:
                line = line.strip()
                if not line:
                    continue
                try:
                    out.append(json.loads(line))
                except ValueError:
                    continue
    except Exception:
        pass
    return out


def now_iso():
    return time.strftime("%Y-%m-%dT%H:%M:%S")


def emit(event_name, text, user_visible=False):
    """Print hook output: additionalContext for the model (and systemMessage for the user)."""
    out = {"hookSpecificOutput": {"hookEventName": event_name, "additionalContext": text}}
    if user_visible:
        out["systemMessage"] = text
    print(json.dumps(out, ensure_ascii=False))


def pick(module, *names):
    """First attribute of `module` that exists among `names` (tolerates API renames)."""
    for n in names:
        fn = getattr(module, n, None)
        if fn is not None:
            return fn
    return None


def run_safely(fn):
    """Run a hook entry point; any unexpected error exits 0 (a hook never breaks a session)."""
    try:
        fn()
    except SystemExit:
        raise
    except Exception:
        pass
